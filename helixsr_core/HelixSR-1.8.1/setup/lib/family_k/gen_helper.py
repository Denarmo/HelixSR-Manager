"""Generate the fast-1x1 helper HIP source for a family kernel from tables/<K>.json (trace_frags.py).

Numerics (identical to family_model.FamilyHook / fast-1x1/model.ChainHook):
  f32: per MMA site, per output (row r, cout o), products in ascending k (k = 8h + 2w + e), each one fp32 FMA
       (v_fma_mix class) into the chain's fp32 accumulator; one fp16 rounding per output at the end of the phase.
  pk : per site and output, two fp16 partial sums (even k / odd k) built with packed fp16 FMAs over the site's k, then
       added into the fp32 accumulator (lo then hi); one fp16 rounding at the end.
Every vector element goes through a scalar before a bit_cast (clang 23 miscompiles __builtin_bit_cast(T, vec[i])).

Segments (tables 'segments'), one device function each, __hx_fam_seg<N>(float *acc, <operands>):
  loop segment : called at the loop header every iteration; A and B rows from LDS at stage-relative offsets.
  line segment : called once, right after the ldmatrix the trace named; A rows from LDS (phase 1) or from the A
                 registers by DPP quad broadcast (phase 2), B rows from LDS.
Blocks: maximal runs of sites with no repeated chain = one k-step of every chain. Site order within a block is free
(each chain still sees its sites in k order): B-major when the block has fewer distinct A than B descriptors (A rows
live, each B row loaded once), else A-major with one-site-ahead B prefetch.
roll=True: when all blocks of a segment follow block 0 (same chains/matrices/base groups, offsets shifted by a
per-block constant that is affine in the block index for LDS-A segments), the segment is emitted as a runtime loop over
blocks (#pragma unroll 1); phase-2 blocks select their A registers and B base by a uniform switch.
Accumulators: per phase one float array; chain index ci -> acc[ci*4 + r*2 + o].
Finals: __hx_fam_final<P>(acc, out): out[2*ci + r] = pack(fp16 acc[ci*4+r*2], fp16 acc[ci*4+r*2+1]).
Usage: gen_helper.py <K> <f32|pk> <out.hip> [--roll]"""
import os as _o, sys as _s; _s.path.insert(0, _o.path.dirname(_o.path.abspath(__file__)))  # helixsr-setup
import json, sys
from pathlib import Path

HDR = r'''// GENERATED by gen_helper.py from the ptxsim-derived fragment tables. NOT bit-exact with the original MMA chains:
// FP32 accumulation (or packed-FP16 partial sums per MMA) and one FP16 rounding per output.
#define FAM_API extern "C" __attribute__((device, always_inline))
#define FAM_LDS __attribute__((address_space(3)))
typedef unsigned famu4 __attribute__((ext_vector_type(4)));
typedef _Float16 famh2 __attribute__((ext_vector_type(2)));
__attribute__((device, always_inline)) static inline famu4 fam_row(unsigned addr) {
  return *(const FAM_LDS famu4 *)(unsigned long)addr;
}
// element through a scalar on purpose (clang 23 bit_cast-of-vector-element miscompile)
__attribute__((device, always_inline)) static inline famh2 fam_h2(famu4 v, unsigned i) {
  const unsigned w = v[i];
  return __builtin_bit_cast(famh2, w);
}
__attribute__((device, always_inline)) static inline famh2 fam_w2(unsigned w) { return __builtin_bit_cast(famh2, w); }
__attribute__((device, always_inline)) static inline unsigned fam_perm(unsigned value, unsigned src) {
  return unsigned(__builtin_amdgcn_ds_bpermute(int(src * 4u), int(value)));
}
__attribute__((device, always_inline)) static inline unsigned fam_quad(unsigned v, unsigned tp) {
  switch (tp) {
  case 0: return unsigned(__builtin_amdgcn_mov_dpp(int(v), 0x00, 15, 15, false));
  case 1: return unsigned(__builtin_amdgcn_mov_dpp(int(v), 0x55, 15, 15, false));
  case 2: return unsigned(__builtin_amdgcn_mov_dpp(int(v), 0xaa, 15, 15, false));
  default: return unsigned(__builtin_amdgcn_mov_dpp(int(v), 0xff, 15, 15, false));
  }
}
__attribute__((device, always_inline)) static inline void fam_addmix(float &d, famh2 p) {
  const unsigned w = __builtin_bit_cast(unsigned, p);
  asm("v_fma_mix_f32 %0, %1, 1.0, %0 op_sel:[0,0,0] op_sel_hi:[1,0,0]" : "+v"(d) : "v"(w));
  asm("v_fma_mix_f32 %0, %1, 1.0, %0 op_sel:[1,0,0] op_sel_hi:[1,0,0]" : "+v"(d) : "v"(w));
}
'''


def layout(t):
    ph = {s['site']: (1 if s['A'][0][0] == 'reg' else 0) for s in t['sites']}
    chains = {0: [], 1: []}
    for s in t['sites']:
        c = s['chain_id']
        if c not in chains[ph[s['site']]]:
            chains[ph[s['site']]].append(c)
    return ph, chains


def blocks_of(ss):
    blocks = []
    for x in ss:
        if not blocks or any(y['chain_id'] == x['chain_id'] for y in blocks[-1]):
            blocks.append([])
        blocks[-1].append(x)
    return blocks


def roll_plan(blocks, regA):
    """None if not rollable; else per block q: (A delta, B delta, B base group for reg-A) relative to block 0."""
    b0 = blocks[0]
    plan = []
    for b in blocks:
        if [x['chain_id'] for x in b] != [x['chain_id'] for x in b0]:
            return None
        da, db, gb = set(), set(), set()
        for x, x0 in zip(b, b0):
            for a, a0 in zip(x['A'], x0['A']):
                if a[0] != a0[0]:
                    return None
                if a[0] == 'lds':
                    if a[1:3] != a0[1:3]:
                        return None
                    da.add(a[3] - a0[3])
            for c, c0 in zip(x['B'], x0['B']):
                if c[1] != c0[1]:
                    return None
                if not regA and c[2] != c0[2]:
                    return None
                gb.add(c[2])
                db.add(c[3] - c0[3])
        if len(da) > 1 or len(db) != 1 or len(gb) != 1:
            return None
        if regA and len({json.dumps(x['A']) for x in b}) != 1:
            return None
        plan.append((da.pop() if da else 0, db.pop(), gb.pop()))
    if not regA:
        sa = plan[1][0] if len(plan) > 1 else 0
        sb = plan[1][1] if len(plan) > 1 else 0
        if any(p[0] != q * sa or p[1] != q * sb for q, p in enumerate(plan)):
            return None
    return plan


def gen(k, mode, roll=False):
    t = json.load(open(Path(__import__('os').environ.get('HELIXSR_FAMILY_TABLES') or (Path(__file__).parent / 'tables')) / f'{k}.json'))
    ph, chains = layout(t)
    sites = {s['site']: s for s in t['sites']}
    k16 = len(t['sites'][0]['A']) == 4
    H = 2 if k16 else 1
    out = [HDR, f'// kernel {k}: {"m16n8k16" if k16 else "m16n8k8"}, phase-1 chains {len(chains[0])}, phase-2 chains {len(chains[1])}, mode {mode}, roll {roll}\n']
    meta = dict(k=k, mode=mode, roll=roll, segments=[], nacc=[4 * len(chains[0]), 4 * len(chains[1])])
    for P in (0, 1):
        n = len(chains[P])
        if not n:
            continue
        out.append(f'FAM_API void __hx_fam_zero{P}(float *acc) {{\n#pragma unroll\n  for (int i = 0; i < {4 * n}; ++i) acc[i] = 0.0f;\n}}\n')
        out.append(f'FAM_API void __hx_fam_final{P}(const float *acc, unsigned *out) {{\n#pragma unroll\n  for (unsigned c = 0; c < {n}; ++c)\n'
                   '#pragma unroll\n    for (unsigned r = 0; r < 2; ++r) {\n'
                   '      famh2 v = {(_Float16)acc[c * 4 + r * 2], (_Float16)acc[c * 4 + r * 2 + 1]};\n'
                   '      out[2 * c + r] = __builtin_bit_cast(unsigned, v);\n    }\n}\n')
    for si, seg in enumerate(t['segments']):
        ss = [sites[x] for x in seg['sites']]
        P = ph[ss[0]['site']]
        assert all(ph[x['site']] == P for x in ss), 'segment mixes phases'
        cmap = {c: i for i, c in enumerate(chains[P])}
        regA = P == 1
        ga = sorted({a[2] for x in ss for a in x['A'] if a[0] == 'lds'})
        gb = sorted({b[2] for x in ss for b in x['B']})
        aregs = []
        for x in ss:
            for a in x['A']:
                if a[0] == 'reg' and a[1] not in aregs:
                    aregs.append(a[1])
        params = ['float *acc'] + [f'unsigned bA{g}' for g in ga] + [f'unsigned bB{g}' for g in gb] + [f'unsigned {r[1:]}' for r in aregs]
        blocks = blocks_of(ss)
        plan = roll_plan(blocks, regA) if (roll and len(blocks) > 1) else None
        body = ['  const unsigned lane = __builtin_amdgcn_mbcnt_lo(~0u, 0u);', '  const unsigned g = lane >> 2, t = lane & 3u;', '  (void)g; (void)t;']
        rows = [0]
        vn = [0]

        def fresh(p):
            vn[0] += 1
            return f'{p}{vn[0]}'
        # address expressions: A row (r,h) of site x; B row (o,h) of site x
        if plan is None:
            pa = sorted({(a[2], a[1]) for x in ss for a in x['A'] if a[0] == 'lds'})
            pb = sorted({(b[2], b[1], o) for x in ss for b in x['B'] for o in (0, 1)})
            for gi, j in pa:
                body.append(f'  const unsigned pA{gi}_{j} = fam_perm(bA{gi}, {8 * j}u + g);')
            for gi, j, o in pb:
                body.append(f'  const unsigned pB{gi}_{j}_{o} = fam_perm(bB{gi}, {8 * j}u + 2u * t + {o}u);')
            a_addr = lambda a: f'pA{a[2]}_{a[1]} + {a[3]}u'
            b_addr = lambda b, o: f'pB{b[2]}_{b[1]}_{o} + {b[3]}u'
            a_reg = lambda a: a[1][1:]
            emit_blocks = blocks
        else:
            b0 = blocks[0]
            emit_blocks = [b0]
            Q = len(blocks)
            loop = [f'#pragma unroll 1', f'  for (unsigned q = 0; q < {Q}u; ++q) {{']
            if not regA:
                pa = sorted({(a[2], a[1]) for x in b0 for a in x['A'] if a[0] == 'lds'})
                pb = sorted({(b[2], b[1], o) for x in b0 for b in x['B'] for o in (0, 1)})
                for gi, j in pa:
                    body.append(f'  const unsigned pA{gi}_{j} = fam_perm(bA{gi}, {8 * j}u + g);')
                for gi, j, o in pb:
                    body.append(f'  const unsigned pB{gi}_{j}_{o} = fam_perm(bB{gi}, {8 * j}u + 2u * t + {o}u);')
                loop.append(f'  const unsigned dA = q * {plan[1][0]}u, dB = q * {plan[1][1]}u;')
                a_addr = lambda a: f'pA{a[2]}_{a[1]} + {a[3]}u + dA'
                b_addr = lambda b, o: f'pB{b[2]}_{b[1]}_{o} + {b[3]}u + dB'
                a_reg = None
            else:
                nA = len(b0[0]['A'])
                loop.append('  unsigned bq; ' + ' '.join(f'unsigned Aq{i};' for i in range(nA)))
                loop.append('  switch (q) {')
                for q, blk in enumerate(blocks):
                    da, db, gq = plan[q]
                    regs = [a[1][1:] for a in blk[0]['A']]
                    sel = ' '.join(f'Aq{i} = {r};' for i, r in enumerate(regs))
                    loop.append(f'  {"default" if q == Q - 1 else f"case {q}"}: bq = bB{gq} + {db}u; {sel} break;')
                loop.append('  }')
                pbq = sorted({(b[1], o) for x in b0 for b in x['B'] for o in (0, 1)})
                for j, o in pbq:
                    loop.append(f'  const unsigned pBq_{j}_{o} = fam_perm(bq, {8 * j}u + 2u * t + {o}u);')
                a_reg = lambda a, _m={a[1]: f'Aq{i}' for i, a in enumerate(b0[0]['A'])}: _m[a[1]]
                b_addr = lambda b, o: f'pBq_{b[1]}_{o} + {b[3]}u'
                a_addr = None
            body += loop

        def arows(x, name):
            lines = []
            for r in range(2):
                for h in range(H):
                    a = x['A'][2 * h + r] if k16 else x['A'][r]
                    if a[0] == 'lds':
                        lines.append(f'  const famu4 {name}_{r}_{h} = fam_row({a_addr(a)});')
                        rows[0] += 1
                    else:   # phase 2: row r, k-half h word tp = quad lane tp's A register (2h + r)
                        reg = a_reg(a)
                        for tp in range(4):
                            lines.append(f'  const unsigned {name}_{r}_{h}_w{tp} = fam_quad({reg}, {tp}u);')
            return lines

        def brows(x, name):
            lines = []
            for o in range(2):
                for h in range(H):
                    lines.append(f'  const famu4 {name}_{o}_{h} = fam_row({b_addr(x["B"][h], o)});')
                    rows[0] += 1
            return lines

        def fmas(x, an, bn):
            ci = cmap[x['chain_id']]
            lines = []
            for r in range(2):
                for o in range(2):
                    acc = f'acc[{ci * 4 + r * 2 + o}]'
                    lines.append(f'  {{ float d = {acc};')
                    if mode == 'pk':
                        lines.append('    famh2 p = {(_Float16)0.0f, (_Float16)0.0f};')
                    for h in range(H):
                        for w in range(4):
                            xa = f'fam_w2({an}_{r}_{h}_w{w})' if regA else f'fam_h2({an}_{r}_{h}, {w}u)'
                            yb = f'fam_h2({bn}_{o}_{h}, {w}u)'
                            if mode == 'pk':
                                lines.append(f'    p = __builtin_elementwise_fma({xa}, {yb}, p);')
                            else:
                                lines.append(f'    {{ const famh2 x = {xa}, y = {yb}; d = __builtin_fmaf(float(x[0]), float(y[0]), d); d = __builtin_fmaf(float(x[1]), float(y[1]), d); }}')
                    if mode == 'pk':
                        lines.append('    fam_addmix(d, p);')
                    lines.append(f'    asm volatile("" : "+v"(d)); {acc} = d; }}')
            return lines

        for blk in emit_blocks:
            adesc = list(dict.fromkeys(json.dumps(x['A']) for x in blk))
            bdesc = list(dict.fromkeys(json.dumps(x['B']) for x in blk))
            if len(adesc) < len(bdesc):
                an = {}
                for ad in adesc:
                    x0 = next(x for x in blk if json.dumps(x['A']) == ad)
                    an[ad] = fresh('a')
                    body += arows(x0, an[ad])
                bn = [fresh('b') for _ in bdesc]
                body += brows(next(x for x in blk if json.dumps(x['B']) == bdesc[0]), bn[0])
                for bi_, bd in enumerate(bdesc):
                    if bi_ + 1 < len(bdesc):
                        body += brows(next(x for x in blk if json.dumps(x['B']) == bdesc[bi_ + 1]), bn[bi_ + 1])
                    for x in blk:
                        if json.dumps(x['B']) == bd:
                            body.append('  {')
                            body += ['  ' + l for l in fmas(x, an[json.dumps(x['A'])], bn[bi_])]
                            body.append('  }')
                    body.append('  __builtin_amdgcn_sched_barrier(0);')
            else:
                groups = []
                for x in blk:
                    key = json.dumps(x['A'])
                    if groups and groups[-1][0] == key:
                        groups[-1][1].append(x)
                    else:
                        groups.append((key, [x]))
                flat = [(gi, x) for gi, (_, xs) in enumerate(groups) for x in xs]
                an = {gi: fresh('a') for gi in range(len(groups))}
                bn = [fresh('b') for _ in flat]
                body += arows(flat[0][1], an[0])
                body += brows(flat[0][1], bn[0])
                for n_, (gi, x) in enumerate(flat):
                    if n_ + 1 < len(flat):
                        ngi, nx = flat[n_ + 1]
                        body += brows(nx, bn[n_ + 1])
                        if ngi != gi:
                            body += arows(nx, an[ngi])
                    body.append('  {')
                    body += ['  ' + l for l in fmas(x, an[gi], bn[n_])]
                    body.append('  }')
                    body.append('  __builtin_amdgcn_sched_barrier(0);')
        if plan is not None:
            body.append('  }')
        nacc = 4 * len(chains[P])
        body.append(f'#pragma unroll\n  for (int i = 0; i < {nacc}; ++i) asm volatile("" : "+v"(acc[i]));')
        out.append(f'FAM_API void __hx_fam_seg{si}(' + ', '.join(params) + ') {\n' + '\n'.join(body) + '\n}\n')
        meta['segments'].append(dict(index=si, kind=seg['kind'], phase=P, sites=[seg['sites'][0], seg['sites'][-1]],
                                     after_ldm_pc=seg.get('after_ldm_pc'), basesA=ga, basesB=gb, aregs=aregs,
                                     lds_rows=rows[0], rolled=plan is not None, blocks=len(blocks)))
    meta['chains'] = {str(P): [t['chains'][c] for c in chains[P]] for P in (0, 1)}
    return ''.join(out), meta


if __name__ == '__main__':
    k, mode, dst = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    src, meta = gen(k, mode, '--roll' in sys.argv)
    dst.write_text(src)
    dst.with_suffix('.json').write_text(json.dumps(meta, indent=1) + '\n')
    print(json.dumps({x: meta[x] for x in ('k', 'mode', 'roll', 'nacc')}), [(s['index'], s['kind'], s['phase'], s['sites'], s['lds_rows'], s['rolled']) for s in meta['segments']])
